"""Server admin CLI.   python manage.py <command>

  init                      generate .env with 3 random secrets (refuses to overwrite)
  create-admin              create/reset the first web admin (prompts for password)
  agent-config --server-url http://HOST:8000   print agent-config.json with the real tokens
  show-secrets              print current secrets (treat output as confidential)
"""
from __future__ import annotations
import argparse, getpass, json, secrets, sys, time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENV = HERE / ".env"


def cmd_init(_):
    if ENV.exists():
        print(f"{ENV} already exists - not overwritten. Delete it first to rotate secrets (agents must be re-configured).")
        return 1
    lines = ["# Generated by manage.py init - NEVER commit or share this file."]
    for k in ("ADMIN", "ENROLLMENT", "DEVICE"):
        lines.append(f"BIMDEPLOY_{k}_TOKEN={secrets.token_urlsafe(48)}")
    lines.append("# BIMDEPLOY_HOME=D:\\BIMDeployment\\data-root")
    ENV.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try: ENV.chmod(0o600)
    except Exception: pass
    print(f"Created {ENV}\nNext: python manage.py create-admin")
    return 0


def _main():
    import main  # loads .env, creates DB
    return main


def cmd_create_admin(a):
    m = _main()
    username = a.username or input("Admin username: ").strip()
    pw = getpass.getpass("Password (12+ chars): "); pw2 = getpass.getpass("Repeat: ")
    if pw != pw2: print("Passwords differ."); return 1
    try: salt, digest = m.password_hash(pw)
    except Exception as e: print("Rejected:", getattr(e, "detail", e)); return 1
    with m.db() as c:
        c.execute("""INSERT INTO users(username,password_salt,password_hash,role,enabled,created_at) VALUES(?,?,?,'admin',1,?)
                     ON CONFLICT(username) DO UPDATE SET password_salt=excluded.password_salt,password_hash=excluded.password_hash,role='admin',enabled=1""",
                  (username, salt, digest, int(time.time())))
        c.execute("DELETE FROM sessions WHERE username=?", (username,))
    print(f"Admin '{username}' ready. Sign in at the web portal.")
    return 0


def cmd_agent_config(a):
    m = _main()
    print(json.dumps({
        "serverUrl": a.server_url.rstrip("/"), "deviceToken": m.DEVICE_TOKEN, "enrollmentToken": m.ENROLLMENT_TOKEN,
        "groups": ["Pilot"], "pollSeconds": 120,
        "installRoot": "C:\\ProgramData\\BIMAddinDeployment\\Addins",
        "statePath": "C:\\ProgramData\\BIMAddinDeployment\\state.json",
        "logPath": "C:\\ProgramData\\BIMAddinDeployment\\agent.log"}, indent=2))
    return 0


def cmd_show(_):
    m = _main()
    print("ADMIN     :", m.ADMIN_TOKEN); print("ENROLLMENT:", m.ENROLLMENT_TOKEN); print("DEVICE    :", m.DEVICE_TOKEN)
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); sp = ap.add_subparsers(dest="cmd", required=True)
    sp.add_parser("init").set_defaults(fn=cmd_init)
    c = sp.add_parser("create-admin"); c.add_argument("--username"); c.set_defaults(fn=cmd_create_admin)
    g = sp.add_parser("agent-config"); g.add_argument("--server-url", required=True); g.set_defaults(fn=cmd_agent_config)
    sp.add_parser("show-secrets").set_defaults(fn=cmd_show)
    a = ap.parse_args(); sys.exit(a.fn(a))
